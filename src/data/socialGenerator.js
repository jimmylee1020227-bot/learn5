// 108 課綱社會科全單元題目引擎（支援會考三科整合、地理奧林匹亞競賽、私中超難題與分級難度）
export function generateSocialQuestion(gradeId, unitId, index, difficulty = 'medium', rand, conceptTag) {
  const isExtreme = difficulty === 'extreme' || difficulty === 'hardest';
  const isHard = difficulty === 'hard';
  const uNum = parseInt(String(unitId).split('-').pop().replace('u', ''), 10) || 1;

  // 動態樂高引擎：產生情境前導詞
  const people = ['阿翔', '小美', '大壯', '阿建', '班長', '老師', '歷史學家', '新聞主播', '公民老師', '小英', '地理資訊研習社'];
  const actions = ['在分析歷屆會考跨歷史、地理、公民三科整合題時', '探討全球地緣政治與經濟貿易協定時', '研讀憲法法庭判決與法治救濟機制時', '判讀高階等高線航照圖與氣候圖表時'];
  const verbs = ['歸納出這道極具深度的思辨考題', '提醒大家切勿落入常見的直覺陷阱', '提出以下這項資料要求大家深入論證', '引導大家從因果脈絡進行客觀推論'];
  
  const person = people[Math.floor(rand() * people.length)];
  const action = actions[Math.floor(rand() * actions.length)];
  const verb = verbs[Math.floor(rand() * verbs.length)];
  const preamble = `${person}${action}，${verb}。`;

  function getRandItems(arr, count) {
    const res = [];
    const pool = [...arr];
    for (let i = 0; i < count; i++) {
      if (pool.length === 0) break;
      const idx = Math.floor(rand() * pool.length);
      res.push(pool.splice(idx, 1)[0]);
    }
    return res;
  }

  // ==========================================
  // 1. 最難試題 (Extreme / Hardest)：會考三科跨領域整合、地理奧林匹亞、私中題
  // ==========================================
  if (isExtreme || gradeId === 'past-exams' || gradeId === 'private-school') {
    if (gradeId === 'g7' || gradeId === 'private-school') {
      // 台灣地理等高線與歷史開港整合題 (會考經典)
      return {
        isReading: true,
        readingText: `【圖表分析-等高線與台灣史跨科素養】\n某地區地形圖顯示：一條河流由東北流向西南，河谷兩側等高線密集且呈現「V」字形向東北方尖端凸出。\n歷史文獻記載，十九世紀中葉（清末開港通商後），外商洋行紛紛於該河流下游沖積平原設立據點，收購山區採集的樟腦與茶葉外銷。\n${preamble}`,
        question: `【會考A++題組-地形判讀與產業經濟綜合分析】下列關於該地區地理環境與歷史發展的敘述，何者完全正確？`,
        options: [
          `等高線V字形尖端指向河流上游，且十九世紀台灣茶與樟腦主要產自北部山坡地與丘陵`,
          `等高線V字形尖端指向河流下游，且此時主要外銷物資為南部甘蔗`,
          `河流流向與等高線無關，且洋行主要由日籍商人獨佔經營`,
          `該平原地區因地形封閉，十九世紀從未與國際貿易市場接軌`
        ],
        answer: 0,
        hint: `💡 提示：河谷等高線的「V」字形尖端必指向地勢較高的上游水源處；清末北台灣因茶與樟腦崛起。`,
        explanation: `📖 詳解：\n1) 等高線通過河谷時會往地勢較高的上游彎曲呈 V 字形，故尖端朝向上游。\n2) 1860年台灣開港通商後，北部丘陵與山區盛產茶葉與樟腦，帶動大稻埕等北部市街繁榮，使台灣經濟重心北移。`
      };
    } else if (gradeId === 'g8' || gradeId === 'past-exams') {
      // 公民法治與憲政體制 (會考壓軸/私中)
      return {
        question: `【會考歷屆經典-權力分立與制衡原理】${preamble}\n我國中央政府體制中，若「立法院」對「行政院院長」提出「不信任案」（倒閣案）並經全體立法委員二分之一以上贊成通過，依據中華民國憲法增修條文規定，後續程序下列何者正確？`,
        options: [
          `行政院院長必須在十日內辭職，並得同時呈請總統解散立法院`,
          `總統必須立刻下台，並由副總統暫代職務`,
          `立法院全體立法委員立即自動解散，且半年內不得改選`,
          `司法院大法官必須召開憲法法庭審查不信任案之合法性`
        ],
        answer: 0,
        hint: `💡 提示：憲法增修條文第 3 條規定，不信任案通過後行政院長辭職，並得呈請總統解散國會。`,
        explanation: `📖 詳解：立法院通過對行政院長的不信任案後，行政院院長應於十日內提出辭職，並得同時呈請總統解散立法院。總統經諮詢立法院院長後得宣告解散立法院。`
      };
    } else {
      // 國三 (g9) 經濟學比較利益與機會成本 (私中奧賽/會考壓軸)
      return {
        isReading: true,
        readingText: `【經濟學經典-李嘉圖比較利益法則】\n甲國與乙國皆生產「晶片」與「小麥」，兩國每位勞工一天的產出如下表：\n===================================\n| 國家 | 晶片 (單位) | 小麥 (單位) |\n| 甲國 |     10      |     20      |\n| 乙國 |      4      |     16      |\n===================================\n${preamble}`,
        question: `【私中/資優挑戰-國際貿易專業化分工】根據「比較利益法則」，兩國應如何進行國際分工以創造最大貿易利得？`,
        options: [
          `甲國生產晶片（機會成本2小麥較低），乙國生產小麥（機會成本1/4晶片較低）`,
          `甲國兩者皆具絕對優勢，故兩國無法從貿易中獲利`,
          `甲國生產小麥，乙國生產晶片`,
          `乙國兩者皆處於絕對劣勢，應完全放棄對外貿易`
        ],
        answer: 0,
        hint: `💡 提示：計算生產一單位晶片的機會成本：甲國=20/10=2小麥；乙國=16/4=4小麥。比較何者機會成本較低。`,
        explanation: `📖 詳解：\n1) 生產1單位晶片的機會成本：甲國為 20/10 = 2 單位小麥；乙國為 16/4 = 4 單位小麥。甲國成本較低，在晶片具比較利益。\n2) 生產1單位小麥的機會成本：甲國為 10/20 = 0.5 單位晶片；乙國為 4/16 = 0.25 單位晶片。乙國成本較低，在小麥具比較利益。\n故甲國專業化生產晶片，乙國專業化生產小麥。`
      };
    }
  }

  // ==========================================
  // 2. 基礎與段考精選試題 (Easy & Medium)
  // ==========================================
  const events = [
    { q: '台灣歷史上「日治時期」始於下列哪一項條約的簽訂？', ans: '中日馬關條約 (1895年)', wrongs: ['辛丑和約', '南京條約', '北京條約'] },
    { q: '在地理學中，判讀地形等高線圖時，等高線愈密集代表：', ans: '地勢坡度愈陡峭', wrongs: ['地勢坡度愈平緩', '海拔高度愈低', '氣溫愈高且雨量愈多'] },
    { q: '市場機制中，當商品價格高於市場均衡價格時，市場將會出現：', ans: '供過於求（市場超額供給）', wrongs: ['供不應求（市場超額需求）', '商品完全缺貨', '消費者競相出高價搶購'] }
  ];
  const eItem = events[Math.floor(rand() * events.length)];

  return {
    question: `【社會科核心素養】${preamble}\n${eItem.q}`,
    options: [eItem.ans, ...getRandItems(eItem.wrongs, 3)],
    answer: 0,
    hint: `💡 提示：回顧 108 課綱社會領域核心史地公概念。`,
    explanation: `📖 詳解：正確選項為「${eItem.ans}」。`
  };
}
