export function getHardScienceQuestion(gradeId, unitId, index, rand, preamble, conceptTag) {
  const uNum = parseInt(String(unitId).split('-').pop().replace(/u/i, ''), 10) || 1;

  if (gradeId === 'g7') {
    // 國一生物極限題
    const g7Archetypes = [
      () => ({
        question: `【跨章節綜合：光合作用與呼吸作用的聯動】${preamble}\n科學家將一株綠色植物置於密閉透明玻璃罩內，連續 24 小時記錄罩內 $CO_2$ 濃度的變化。已知白天有光照，夜晚無光照。若圖表顯示清晨 6:00 $CO_2$ 濃度達到最高峰，下午 14:00 $CO_2$ 濃度降至最低點，則下列推論何者最符合科學事實？`,
        options: [
          `清晨 6:00 時，植物的呼吸作用速率等於光合作用速率（光補償點）`,
          `下午 14:00 時，植物完全停止呼吸作用，只進行光合作用`,
          `從 6:00 到 14:00，植物體內的有機養分總量持續減少`,
          `夜晚期間植物進行碳反應釋放 $CO_2$，導致濃度上升`
        ],
        answer: 0,
        hint: `💡 提示：濃度達到轉折點（最高或最低），代表消耗與產生的速率剛好相等。`,
        explanation: `📖 詳解：清晨 6:00 是夜間累積 $CO_2$ 的最高點，此時隨著光線出現，光合速率開始大於呼吸速率，$CO_2$ 開始下降，因此 6:00 恰為光合速率＝呼吸速率的光補償點。下午 14:00 同理，為傍晚的光補償點。植物無時無刻都在進行呼吸作用。`
      }),
      () => {
        const temp = Math.floor(rand() * 10) + 40; // 40-50度
        return {
          question: `【酵素動力學極端條件】${preamble}\n人體胃液中的胃蛋白酶最適 pH 值約為 2。若將胃蛋白酶置於 pH=8 且溫度為 $${temp}^\\circ C$ 的緩衝液中長達 3 小時，隨後迅速將環境調整回 pH=2 且 $37^\\circ C$ 並加入蛋白質，請問反應結果為何？`,
          options: [
            `幾乎無催化活性，因長時間處於極端鹼性與高溫，蛋白質結構已產生不可逆的變性`,
            `催化活性比正常更高，因為 $${temp}^\\circ C$ 的熱能被儲存為活化能`,
            `活性完全恢復，因為酵素具有自動修復立體結構的特性`,
            `只能將蛋白質分解為胺基酸，無法分解為多肽`
          ],
          answer: 0,
          hint: `💡 提示：酵素為蛋白質，受到極端酸鹼或高溫破壞其 3D 結構後，即便回到最適環境也無法復原。`,
          explanation: `📖 詳解：高溫與極端不適的 pH 值都會破壞酵素（蛋白質）的立體結構（變性），這是不可逆的物理化學變化，故調回最適條件依然無活性。`
        };
      },
      () => ({
        question: `【遺傳學高階推論：性聯遺傳與譜系】${preamble}\n紅綠色盲是一種隱性性聯遺傳疾病（基因位於 X 染色體）。若一對視覺正常的夫婦，生下一個患有紅綠色盲的兒子。已知妻子的父親患有色盲，請問這對夫婦若再生一個女兒，該女兒患有紅綠色盲的機率為何？`,
        options: [
          `0%`,
          `25%`,
          `50%`,
          `100%`
        ],
        answer: 0,
        hint: `💡 提示：丈夫正常 (X^Y)，女兒必定從父親得到正常的 X 染色體。`,
        explanation: `📖 詳解：父親視覺正常，基因型必為 $X^B Y$。女兒一定會從父親遺傳到一個正常的 $X^B$，因此無論母親給什麼基因（母親為帶因者 $X^B X^b$），女兒基因型為 $X^B X^B$ 或 $X^B X^b$，視覺表現皆為正常（0% 色盲機率）。`
      })
    ];
    return g7Archetypes[Math.abs(index + Math.floor(rand() * 17)) % g7Archetypes.length]();
  }

  if (gradeId === 'g8') {
    // 國二理化極限題
    const g8Archetypes = [
      () => {
        const v = Math.floor(rand() * 50) + 100; // 100-150 mL
        const m = Math.floor(rand() * 30) + 20;  // 20-50 g
        const d_metal = Math.floor(rand() * 5) + 3; // 3-7 g/cm^3
        const m_metal = m * d_metal;
        return {
          question: `【密度混合進階計算】${preamble}\n有一個體積為 ${v} $cm^3$ 的量筒，裝有 $V_1$ 體積的純水（密度 $1.0 g/cm^3$）。將一個質量為 ${m_metal} g$、密度為 ${d_metal} $g/cm^3$ 的金屬塊完全沉入水中，若水剛好滿至量筒邊緣而未溢出，請問量筒內最初裝有多少質量的水？`,
          options: [
            `${v - m} g`,
            `${v - m_metal} g`,
            `${v - m/d_metal} g`,
            `${v} g`
          ],
          answer: 0,
          hint: `💡 提示：金屬塊的體積 = 質量 / 密度 = ${m_metal} / ${d_metal} = ${m} $cm^3$。`,
          explanation: `📖 詳解：金屬體積 $V_m = \\frac{${m_metal}}{${d_metal}} = ${m} \\, cm^3$。水剛好滿出，代表最初水的體積 $V_{water} = 總體積 - 金屬體積 = ${v} - ${m} = ${v - m} \\, cm^3$。水的密度為 1，故質量為 ${v - m} g$。`
        };
      },
      () => {
        const c1 = Math.floor(rand() * 5) + 2; // 2-6 %
        const w1 = Math.floor(rand() * 100) + 100; // 100-200 g
        const c2 = Math.floor(rand() * 10) + 10; // 10-20 %
        const w2 = Math.floor(rand() * 100) + 100; // 100-200 g
        const solute = (c1 * w1 / 100) + (c2 * w2 / 100);
        const finalC = ((solute / (w1 + w2)) * 100).toFixed(1);
        return {
          question: `【濃度混合與精確化學計量】${preamble}\n將 ${w1} g 濃度為 ${c1}% 的食鹽水與 ${w2} g 濃度為 ${c2}% 的食鹽水混合，並將混合液加熱蒸發掉 10 g 的水。請問最終食鹽水的重量百分濃度最接近下列何者？`,
          options: [
            `${((solute / (w1 + w2 - 10)) * 100).toFixed(1)}%`,
            `${finalC}%`,
            `${((c1 + c2) / 2).toFixed(1)}%`,
            `${(((c1 * w1 + c2 * w2) / (w1 + w2 + 10)) * 100).toFixed(1)}%`
          ],
          answer: 0,
          hint: `💡 提示：先算出總溶質質量，再除以（總重量 - 蒸發的水重）。`,
          explanation: `📖 詳解：原溶質 $1 = ${w1} \\times ${c1}\\% = ${c1 * w1 / 100}g$。原溶質 $2 = ${w2} \\times ${c2}\\% = ${c2 * w2 / 100}g$。總溶質 = ${solute}g。最終溶液重 = ${w1} + ${w2} - 10 = ${w1 + w2 - 10}g。濃度 = $\\frac{${solute}}{${w1 + w2 - 10}} \\times 100\\% \\approx ${((solute / (w1 + w2 - 10)) * 100).toFixed(1)}\\%$。`
        };
      },
      () => ({
        question: `【力學與摩擦力臨界狀態分析】${preamble}\n一個重量為 $W$ 的木塊靜置於水平桌面上，若施加一水平拉力 $F$，當 $F = 10 N$ 時，木塊恰好開始滑動；當木塊滑動後，只需 $8 N$ 的水平拉力即可維持等速度運動。若在木塊上放置另一個重量相同的木塊，請問下列敘述何者錯誤？`,
        options: [
          `木塊開始滑動的瞬間，動摩擦力為 $10 N$`,
          `最大靜摩擦力變為 $20 N$`,
          `維持等速度運動所需的拉力變為 $16 N$`,
          `正向力增加為原本的 2 倍`
        ],
        answer: 0,
        hint: `💡 提示：啟動瞬間克服的是「最大靜摩擦力」，滑動後才是「動摩擦力」。`,
        explanation: `📖 詳解：恰開始滑動時的拉力等於「最大靜摩擦力」($10 N$)，滑動後等速所需拉力等於「動摩擦力」($8 N$)。選項(A)錯誤，啟動瞬間克服的是最大靜摩擦力，而非動摩擦力。重量加倍時，正向力加倍，各種摩擦力亦隨之加倍。`
      })
    ];
    return g8Archetypes[Math.abs(index + Math.floor(rand() * 17)) % g8Archetypes.length]();
  }

  if (gradeId === 'g9') {
    // 國三地科與進階理化
    const g9Archetypes = [
      () => ({
        question: `【運動學極限：相對運動與加速度】${preamble}\n甲車以 $30 m/s$ 的等速度在直線公路上行駛，當甲車經過靜止的乙車時，乙車立即以 $5 m/s^2$ 的等加速度與甲車同向啟動追趕。請問乙車追上甲車所需的時間，以及追上時乙車的速度分別為多少？`,
        options: [
          `時間：12 秒，速度：60 m/s`,
          `時間：6 秒，速度：30 m/s`,
          `時間：12 秒，速度：30 m/s`,
          `時間：10 秒，速度：50 m/s`
        ],
        answer: 0,
        hint: `💡 提示：追上時兩車位移相等：$V_{甲} \\times t = \\frac{1}{2} a_{乙} t^2$。`,
        explanation: `📖 詳解：設 $t$ 秒後追上，甲車位移 $S_1 = 30t$，乙車位移 $S_2 = \\frac{1}{2} \\times 5 \\times t^2$。相遇時 $S_1 = S_2$，故 $30t = 2.5t^2 \\Rightarrow t = 12$ 秒（$t=0$為出發點）。追上時乙車速度 $V = a \\times t = 5 \\times 12 = 60 m/s$。`
      }),
      () => ({
        question: `【天文地科高階：星系與光年】${preamble}\n天文學家觀察到某個遙遠星系的光譜產生了「紅移」現象，且該星系距離地球約 200 萬光年。下列關於此天文現象的推論，何者完全正確？`,
        options: [
          `紅移現象表示該星系正遠離我們，且我們現在看到的是它 200 萬年前的狀態`,
          `紅移現象表示該星系正靠近我們，且我們現在看到的是它 200 萬年前的狀態`,
          `紅移現象表示該星系正遠離我們，且我們現在看到的是它目前的狀態`,
          `紅移現象表示該星系正靠近我們，且光速因紅移而變慢`
        ],
        answer: 0,
        hint: `💡 提示：都卜勒效應中，光源遠離波長變長（紅移）；光年是距離單位，光走 200 萬年代表我們看到的是舊影像。`,
        explanation: `📖 詳解：宇宙膨脹導致遙遠星系遠離地球，光波被拉長產生「紅移」。距離 200 萬光年代表光旅行了 200 萬年才到達地球，因此我們看到的是該星系 200 萬年前的模樣。`
      }),
      () => {
        const v = Math.floor(rand() * 100) + 100;
        const i = Math.floor(rand() * 5) + 2;
        return {
          question: `【電學綜合：功率與焦耳定律】${preamble}\n將一個標示為「${v}V, ${v*i}W」的電熱水瓶，接在 ${v}V 的電源上連續加熱 5 分鐘。若電能完全轉換為熱能，且沒有熱量散失，請問此過程中共產生了多少焦耳的熱能？`,
          options: [
            `${v*i * 300}`,
            `${v*i * 5}`,
            `${v*i * 60}`,
            `${v*i}`
          ],
          answer: 0,
          hint: `💡 提示：電能（熱能） = 電功率 (W) × 時間 (秒)。`,
          explanation: `📖 詳解：功率 $P = ${v*i} W$，時間 $t = 5 \\times 60 = 300$ 秒。產生的熱能 $E = P \\times t = ${v*i} \\times 300 = ${v*i*300}$ 焦耳。`
        };
      }
    ];
    return g9Archetypes[Math.abs(index + Math.floor(rand() * 17)) % g9Archetypes.length]();
  }

  // Fallback
  return {
    question: `【國中自然極限綜合挑戰】${preamble}\n下列哪一種現象無法用「牛頓第三運動定律（作用力與反作用力）」來解釋？`,
    options: [
      `物體在真空中自由落下時，加速度恆定為 $g$`,
      `火箭噴出高溫氣體而向上升空`,
      `人在平滑溜冰場上向前推牆，自己卻向後退`,
      `船槳向後撥水，船體向前行駛`
    ],
    answer: 0,
    hint: `💡 提示：自由落體是受到地球萬有引力作用，與反作用力推動無關。`,
    explanation: `📖 詳解：自由落體加速度恆定是因為受到固定的重力（萬有引力）影響，這是牛頓第二運動定律 ($F=ma$) 的體現。其餘三者皆為標準的作用力與反作用力現象。`
  };
}
