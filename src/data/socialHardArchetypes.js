export function getHardSocialQuestion(gradeId, unitId, index, rand, preamble, conceptTag) {
  const uNum = parseInt(String(unitId).split('-').pop().replace(/u/i, ''), 10) || 1;

  if (gradeId === 'g7') {
    const archetypes = [
      () => ({
        question: `【史地綜合：大航海時代與台灣地理】${preamble}\n17 世紀，荷蘭東印度公司在台灣建立統治據點。若當時有一艘荷蘭商船從印尼巴達維亞（今雅加達）出發，預計經由台灣前往日本長崎貿易。下列關於該航線與台灣地理特徵的敘述，何者最為正確？`,
        options: [
          `船隻途經台灣海峽時，夏季易受西南季風順風之助航向日本`,
          `荷蘭人選擇在台灣北部（今基隆、淡水）建立首個據點，是因為該處無黑水溝阻隔`,
          `台灣西南部海岸多岩岸，水深港闊，非常適合大型商船停泊`,
          `船隻抵達台灣時，首遇的原住民主要為高山族群（如泰雅族、布農族）`
        ],
        answer: 0,
        hint: `💡 提示：台灣夏季吹西南季風，冬季吹東北季風；荷蘭據點在南部（大員）；西南部為沙岸。`,
        explanation: `📖 詳解：(A) 夏季西南季風由南向北吹，剛好順風前往台灣及日本。(B) 荷蘭首個據點在南部的大員（台南安平），北部據點主要是西班牙人建立。(C) 台灣西南部為沙岸，水淺不適合大船，需小船接駁。(D) 荷蘭人最先接觸的是平埔族群（如西拉雅族）。`
      })
    ];
    return archetypes[Math.abs(index + Math.floor(rand() * 11)) % archetypes.length]();
  }

  // Fallback for Social Hard
  return {
    question: `【公民與法律高階實例題】${preamble}\n某知名 YouTuber 未經授權，將他人拍攝的電影剪輯成「五分鐘看完一部電影」的短片並上傳營利。原著作權人決定提告。下列關於此案的法律責任與權利主張，何者完全正確？`,
    options: [
      `原著作權人可同時提起刑事告訴與民事損害賠償訴訟`,
      `YouTuber 只要在影片標註「影片來源：某某電影」，即完全符合著作權法之合理使用`,
      `此為告訴乃論之罪，若檢察官提起公訴，原著作權人就不能再要求民事賠償`,
      `著作權屬於絕對權，任何人不得以任何理由進行改作或引用`
    ],
    answer: 0,
    hint: `💡 提示：侵害著作權屬犯罪行為，且同時造成財產損失；合理使用有嚴格條件。`,
    explanation: `📖 詳解：(A) 侵害著作權可同時構成刑事犯罪（違反著作權法）與民事侵權行為，權利人可同時主張。(B) 標示來源不代表合法授權或必定符合合理使用。(C) 刑事訴訟與民事訴訟為兩條獨立途徑，可提出「附帶民事訴訟」。(D) 著作權法設有「合理使用」條款（如教育、評論），並非絕對不可引用。`
  };
}
