        hint: `💡 提示：梅雨是冷暖氣團勢均力敵形成的滯留鋒面。`,
        explanation: `📖 詳解：梅雨季由南方暖濕氣團與北方冷氣團交會，兩者勢力相當形成「滯留鋒」，造成持續性降雨。`
