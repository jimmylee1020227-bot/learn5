        hint: `💡 提示：夏至直射北回歸線 (晝最長夜最短)；冬至直射南回歸線；春分秋分直射赤道。`,
        explanation: `📖 詳解：夏至太陽直射北回歸線 (23.5°N)，北半球白晝時間達到一年中最長，正午太陽仰角最高。`
