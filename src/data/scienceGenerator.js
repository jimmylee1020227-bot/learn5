        answer: 0,
        hint: `💡 提示：體積增加 20 cm³，質量增加 16 g ⇒ 密度 = 16 ÷ 20 = 0.8 g/cm³。量筒重 = 總重 - 液體重。`,
        explanation: `📖 詳解：ΔM = 80 - 64 = 16 g，ΔV = 50 - 30 = 20 cm³。液體密度 D = 16 / 20 = 0.8 g/cm³。量筒質量 = 64 - (30 × 0.8) = 64 - 24 = 40 g。`
