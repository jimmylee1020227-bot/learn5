export function getHardChineseQuestion(gradeId, unitId, index, rand, preamble, conceptTag) {
  const uNum = parseInt(String(unitId).split('-').pop().replace(/u/i, ''), 10) || 1;

  if (gradeId === 'g7') {
    const archetypes = [
      () => ({
        question: `【文言文修辭進階：借代與雙關】${preamble}\n「何以解憂？唯有杜康。」句中「杜康」借代為酒。下列何者也使用了「借代」修辭，且借代的主體為「書信」？`,
        options: [
          `客從遠方來，遺我「雙鯉魚」`,
          `朱門酒肉臭，路有「凍死骨」`,
          `過盡千帆皆不是，斜暉脈脈水「悠悠」`,
          `「布衣」可致卿相`
        ],
        answer: 0,
        hint: `💡 提示：古人常將書信藏於木雕成魚形的函中。`,
        explanation: `📖 詳解：(A)「雙鯉魚」借代為書信（信函）。(B)「凍死骨」借代為因寒冷飢餓而死的人；(C) 無借代；(D)「布衣」借代為平民百姓。`
      }),
      () => ({
        question: `【字音字形高難度辨析】${preamble}\n下列選項「」中的字，何者讀音完全相同？`,
        options: [
          `「稗」官野史／「俾」晝作夜`,
          `「朔」氣傳金柝／撲「朔」迷離`,
          `「鍥」而不捨／提綱「挈」領`,
          `「否」極泰來／臧「否」人物`
        ],
        answer: 3,
        hint: `💡 提示：(D) 否極泰來（ㄆㄧˇ）；臧否人物（ㄆㄧˇ）。`,
        explanation: `📖 詳解：(A) ㄅㄞˋ／ㄅㄧˋ。(B) ㄕㄨㄛˋ／ㄕㄨㄛˋ。(C) ㄑㄧㄝˋ／ㄑㄧㄝˋ。(D) 皆讀 ㄆㄧˇ，皆作「不好、壞」解。等等，(B) 皆讀 ㄕㄨㄛˋ！(C) 鍥：ㄑㄧㄝˋ，挈：ㄑㄧㄝˋ！這題設計陷阱較深，標準答案設定為(D)考多音字「否」ㄆㄧˇ。實際上(B)與(D)皆同音。為了確保選項唯一，我們將(B)改為「朔」氣/「塑」膠 (ㄕㄨㄛˋ/ㄙㄨˋ)。將(C)改為 鍥/契 (ㄑㄧㄝˋ/ㄑㄧˋ)。正確答案為(D)。`
      })
    ];
    // Dynamic fix for archetype 1
    const q1 = archetypes[1]();
    q1.options = [
      `「稗」官野史／「俾」晝作夜`,
      `「朔」氣傳金柝／「塑」化劑`,
      `「鍥」而不捨／「契」合`,
      `「否」極泰來／臧「否」人物`
    ];
    q1.explanation = `📖 詳解：(A) ㄅㄞˋ／ㄅㄧˋ。(B) ㄕㄨㄛˋ／ㄙㄨˋ。(C) ㄑㄧㄝˋ／ㄑㄧˋ。(D) 兩者皆讀「ㄆㄧˇ」，「否極泰來」指壞運到了盡頭；「臧否人物」指褒貶評論人物。`;
    archetypes[1] = () => q1;
    return archetypes[Math.abs(index + Math.floor(rand() * 11)) % archetypes.length]();
  }

  // Fallback for Chinese Hard
  return {
    question: `【國文學測級：語意與邏輯綜合】${preamble}\n閱讀以下短文：「世之言道者，或即其所見而名之，或莫之見而意之。皆不足以盡道。」\n依據上文，作者認為「言道者」之所以「不足以盡道」，其根本原因為何？`,
    options: [
      `過度依賴主觀經驗或憑空臆測`,
      `無法將抽象的道轉化為具體的文字`,
      `見識淺薄且缺乏實踐精神`,
      `各家學派意見分歧無法統一`
    ],
    answer: 0,
    hint: `💡 提示：「即其所見」指依賴個人所見；「莫之見而意之」指沒有看見就憑空猜想。`,
    explanation: `📖 詳解：文意指出，談論「道」的人，有的只根據自己有限的見聞來命名（即其所見），有的根本沒看見就憑空猜測（莫之見而意之），這兩種都流於主觀與臆測，因此無法窮盡「道」的真理。`
  };
}
